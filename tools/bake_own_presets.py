#!/usr/bin/env python3
"""Bakes ilana's own preset files into src/PresetPackIlanaOwn.h as factory
presets that load exactly as the file does (FactoryPreset::savedState).

The state is the file's, cut to what a load reads back the same: the
parameters that differ from their defaults (a load fills the rest with the
defaults) and every attribute but the default drawn LFO shapes and curves.

    ILANA_DUMP_DEFAULTS=build/gen/defaults.txt ilanaPresetRender x
    python3 tools/bake_own_presets.py

Append to OWN, never reorder it: factory indices never move.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import preset_gen as gen  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
USER = ROOT / "content" / "user-presets"
OUT = ROOT / "src" / "PresetPackIlanaOwn.h"

# (factory name, her file, category, tags, what it is, parameters added)
# The added parameters only wire a macro her file names but leaves unrouted
# (every factory macro must move something); at the macro's rest they change
# nothing, so the preset sounds as her file does.
OWN = [
    ("Deep Grit 808", "Distorted 808_fixed", "Bass", "Gritty, Glide, Warm, Percussive, Wavetable",
     "her own 808 (2026-11-09): the sub on, the filter shut to 50 Hz and a quicker glide; a new sound, not a fix of Distorted 808",
     # TONE (macro 2, source 13) opens Filter 1 (destination 9) by up to ~4 octaves
     {"mod8_src": "13", "mod8_dst": "9", "mod8_amt": "0.4"}),
]

DEFAULT_DRAW = None


def minimal_state(path, name, category, tags, defaults, extra):
    root = ET.parse(path).getroot()
    out = ET.Element(root.tag)
    sine = ",".join(f"{v:.5f}" for v in (__import__("math").sin(2 * __import__("math").pi * i / 64) for i in range(64)))
    for key, value in root.attrib.items():
        if key.endswith("Draw") and value.replace("-0.00000", "0.00000") == sine.replace("-0.00000", "0.00000"):
            continue
        if key.endswith("Curve") and value == gen.DEFAULT_CURVE:
            continue
        out.set(key, value)
    out.set("presetName", name)
    out.set("presetCategory", category)
    out.set("presetTags", tags)
    for child in root:
        if child.tag != "PARAM":
            out.append(child)
            continue
        pid = child.get("id")
        try:
            value = float(child.get("value"))
        except (TypeError, ValueError):
            continue
        if pid in defaults and abs(value - defaults[pid]) <= 1e-6 * max(1.0, abs(defaults[pid])):
            continue
        if pid in extra:
            continue
        ET.SubElement(out, "PARAM", {"id": pid, "value": child.get("value")})
    for pid, value in extra.items():
        ET.SubElement(out, "PARAM", {"id": pid, "value": value})
    return ET.tostring(out, encoding="unicode")


def main():
    defaults = gen.read_defaults()
    lines = [
        "#pragma once",
        "",
        "// ilana's own presets in the factory list, as she made them: each carries",
        "// her saved file's state and loads as that file does. Generated by",
        "// tools/bake_own_presets.py from content/user-presets; edit the script, not",
        "// this file. Appended after every earlier preset (indices never move).",
        "// Included from PresetLibrary.h inside Presets::Library.",
        "",
        "inline void addIlanaOwnPresets (const std::function<void (const FactoryPreset&)>& add)",
        "{",
    ]
    for name, stem, category, tags, about, extra in OWN:
        state = minimal_state(USER / f"{stem}.ilanapreset", name, category, tags, defaults, extra)
        assert ")ilana\"" not in state
        lines += [
            f"    // {about} (from \"{stem}\")",
            "    {",
            f"        FactoryPreset p {{ {gen.cpp_string(name)}, {{}} }};",
            f"        p.category = {gen.cpp_string(category)};",
            # the browser lists macro names from here, without loading the state
            "        p.macroNames = { " + ", ".join(gen.cpp_string(ET.fromstring(state).get(f"macroName{i}", ""))
                                              for i in range(1, 9)) + " };",
            f"        p.savedState = R\"ilana({state})ilana\";",
            "        add (p);",
            "    }",
        ]
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"baked {len(OWN)} presets into {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
