static double levelDb (int midi, double u, float seed)
{
    constexpr double rate = 48000.0;
    auto m = std::make_unique<ModalBowed>();
    m->prepare (rate);
    m->setSizeLevel (false);
    m->setShape ((float) std::pow (ModalBowedBodies::cello, u), 1.0f);
    m->setParams (0.75f, 0.35f, 0.0f, 0.0f, 0.5f, 0.5f, 0.0f, false, false, 0.5f, 0.0f);
    m->setNote (440.0 * std::pow (2.0, (midi - 69) / 12.0));
    m->trigger (0.8f, seed);
    auto sum = 0.0;
    const auto from = (int) (1.0 * rate), to = (int) (3.5 * rate);
    for (int i = 0; i < to; ++i)
    {
        const auto v = (double) m->process (0.0f, true);
        if (i >= from)
            sum += v * v;
    }
    return 10.0 * std::log10 (sum / (to - from) + 1.0e-30);
}

using L = ModalBowedSizeLevel;
constexpr float seeds[] { 0.37f, 0.71f, 0.13f };
constexpr double beyondCap = 18.0;

// (power mean over the seeds)
static double meanDb (int midi, double u)
{
    auto power = 0.0;
    for (auto seed : seeds)
        power += std::pow (10.0, levelDb (midi, u, seed) / 10.0) / std::size (seeds);
    return 10.0 * std::log10 (power);
}

// The u of a beyond knot: k 0 the violin's (u 0), k 1 the cello's (u 1),
// then the above knots, then the below.
static double beyondU (int k)
{
    if (k < 2)
        return (double) k;
    k -= 2;
    return k < L::aboveCount ? 1.0 + (double) (k + 1) / L::beyondKnots : -(double) (k - L::aboveCount + 1) / L::beyondKnots;
}
constexpr int beyondJobs = 2 + L::aboveCount + L::belowCount;

static void runJobs (int jobs, int threads, const std::function<void (int)>& job)
{
    std::atomic<int> next { 0 };
    std::vector<std::thread> pool;
    for (int t = 0; t < threads; ++t)
        pool.emplace_back ([&] { for (int j; (j = next++) < jobs;) job (j); });
    for (auto& t : pool)
        t.join();
}

// The header: the fitted span's rows (cello: each note's dB at u 1, for the
// above knots' anchor), then the beyond knots from each note's measured
// levels at beyondU (levels[note][k]).
static bool writeHeader (const char* path, const std::vector<std::string>& rows, const std::vector<double>& atCello, const std::vector<std::vector<double>>& levels)
{
    const int notes = L::last - L::first + 1;
    auto* out = std::fopen (path, "w");
    if (out == nullptr) { std::fprintf (stderr, "can't write %s\n", path); return false; }
    std::fprintf (out, "// Generated by tools/modal_bowed_refit/size_level.cpp: do not edit.\n#pragma once\n\n"
                       "// SIZE's loudness for Modal Bowed: per MIDI note (first..last, held past\n"
                       "// either end), the dB at u = k / knots (k 1..knots; 0 at k 0, held past\n"
                       "// knots) that keeps a bowed note at one level along SIZE, the violin's\n"
                       "// (its anchor). Past the fitted bodies (above: u 1 + (k + 1) / beyondKnots,\n"
                       "// below: u -(k + 1) / beyondKnots, held past the last) the dB that keeps\n"
                       "// it at the nearer end's level. See ModalBowed::sizeLevelDb.\n"
                       "struct ModalBowedSizeLevel\n{\n"
                       "    static constexpr int knots = %d, first = %d, last = %d;\n"
                       "    static constexpr float db[last - first + 1][knots] {\n", L::knots, L::first, L::last);
    for (const auto& row : rows)
        std::fprintf (out, "%s\n", row.c_str());
    std::fprintf (out, "    };\n    static constexpr int beyondKnots = %d, aboveCount = %d, belowCount = %d;\n", L::beyondKnots, L::aboveCount, L::belowCount);
    const auto cap = [] (double db) { return std::clamp (db, -beyondCap, beyondCap); };
    // (each knot's level the mean (dB) of it and its neighbours on its side,
    // the end's own level next to the first: past the fitted bodies the
    // modes are narrow, and a partial landing on one at a knot is luck)
    const auto smoothed = [] (const std::vector<double>& v, int end, int first, int count, int k)
    {
        const auto at = [&] (int i) { return i < 0 ? v[(size_t) end] : v[(size_t) (first + std::min (i, count - 1))]; };
        return (at (k - 1) + at (k) + at (k + 1)) / 3.0;
    };
    std::fprintf (out, "    static constexpr float above[last - first + 1][aboveCount] {\n");
    for (int n = 0; n < notes; ++n)
    {
        const auto& v = levels[(size_t) n];
        const auto target = v[1] + atCello[(size_t) n];
        std::fprintf (out, "        {");
        for (int k = 0; k < L::aboveCount; ++k)
            std::fprintf (out, " %.2ff%s", cap (target - smoothed (v, 1, 2, L::aboveCount, k)), k < L::aboveCount - 1 ? "," : "");
        std::fprintf (out, " }%s   // %d\n", n < notes - 1 ? "," : "", L::first + n);
    }
    std::fprintf (out, "    };\n    static constexpr float below[last - first + 1][belowCount] {\n");
    for (int n = 0; n < notes; ++n)
    {
        const auto& v = levels[(size_t) n];
        std::fprintf (out, "        {");
        for (int k = 0; k < L::belowCount; ++k)
            std::fprintf (out, " %.2ff%s", cap (v[0] - smoothed (v, 0, 2 + L::aboveCount, L::belowCount, k)), k < L::belowCount - 1 ? "," : "");
        std::fprintf (out, " }%s   // %d\n", n < notes - 1 ? "," : "", L::first + n);
    }
    std::fprintf (out, "    };\n};\n");
    std::fclose (out);
    return true;
}

// The fitted span's rows as they stand in the header (the --merge path keeps them, comments and all).
static std::vector<std::string> headerRows (const char* path)
{
    std::vector<std::string> rows;
    if (auto* in = std::fopen (path, "r"))
    {
        char line[8192];
        auto inside = false;
        while (std::fgets (line, sizeof (line), in) != nullptr)
        {
            std::string s (line);
            if (! s.empty() && s.back() == '\n')
                s.pop_back();
            if (s.find ("db[last - first + 1][knots]") != std::string::npos) { inside = true; continue; }
            if (inside && s.rfind ("    };", 0) == 0)
                break;
            if (inside)
                rows.push_back (s);
        }
        std::fclose (in);
    }
    return rows;
}

int main (int argc, char** argv)
{
    if (argc > 1 && std::strcmp (argv[1], "--beyond") == 0)
    {
        if (argc < 5) { std::fprintf (stderr, "usage: size_level --beyond part.csv first last [threads]\n"); return 1; }
        const int from = std::atoi (argv[3]), to = std::atoi (argv[4]), threads = argc > 5 ? std::atoi (argv[5]) : 3;
        ModalBowedLayers::bankFor (48000.0);
        ModalBowedLayers::waitUntilBuilt();
        const int count = to - from + 1;
        std::vector<double> db ((size_t) (count * beyondJobs));
        runJobs (count * beyondJobs, threads, [&] (int job) { db[(size_t) job] = meanDb (from + job / beyondJobs, beyondU (job % beyondJobs)); });
        auto* csv = std::fopen (argv[2], "w");
        if (csv == nullptr) return 1;
        for (int n = 0; n < count; ++n)
        {
            std::fprintf (csv, "%d", from + n);
            for (int k = 0; k < beyondJobs; ++k)
                std::fprintf (csv, ",%.4f", db[(size_t) (n * beyondJobs + k)]);
            std::fprintf (csv, "\n");
        }
        std::fclose (csv);
        return 0;
    }
    if (argc > 1 && std::strcmp (argv[1], "--merge") == 0)
    {
        if (argc < 4) { std::fprintf (stderr, "usage: size_level --merge out.h part.csv...\n"); return 1; }
        const int notes = L::last - L::first + 1;
        std::vector<std::vector<double>> levels ((size_t) notes);
        for (int a = 3; a < argc; ++a)
            if (auto* csv = std::fopen (argv[a], "r"))
            {
                char line[8192];
                while (std::fgets (line, sizeof (line), csv) != nullptr)
                {
                    std::vector<double> v;
                    for (char* s = std::strtok (line, ",\n"); s != nullptr; s = std::strtok (nullptr, ",\n"))
                        v.push_back (std::atof (s));
                    if ((int) v.size() == beyondJobs + 1 && (int) v[0] >= L::first && (int) v[0] <= L::last)
                        levels[(size_t) ((int) v[0] - L::first)].assign (v.begin() + 1, v.end());
                }
                std::fclose (csv);
            }
        std::vector<double> atCello ((size_t) notes);
        for (int n = 0; n < notes; ++n)
        {
            if (levels[(size_t) n].empty()) { std::fprintf (stderr, "no levels for %d\n", L::first + n); return 1; }
            atCello[(size_t) n] = L::db[n][L::knots - 1];
        }
        const auto rows = headerRows (argv[2]);
        if ((int) rows.size() != notes) { std::fprintf (stderr, "can't read the span's rows from %s\n", argv[2]); return 1; }
        return writeHeader (argv[2], rows, atCello, levels) ? 0 : 1;
    }

    if (argc < 2) { std::fprintf (stderr, "usage: size_level out.h [threads] [levels.csv]\n"); return 1; }
    const int threads = argc > 2 ? std::atoi (argv[2]) : 3;
    const int notes = L::last - L::first + 1;
    constexpr int violinFirst = 55, gapSmooth = 4;
    constexpr double easeTo = 0.25;
    ModalBowedLayers::bankFor (48000.0);
    ModalBowedLayers::waitUntilBuilt();
    std::vector<double> db ((size_t) (notes * (L::knots + 1)), 0.0);
    std::atomic<int> next { 0 };
    std::vector<std::thread> pool;
    for (int t = 0; t < threads; ++t)
        pool.emplace_back ([&]
        {
            for (int job; (job = next++) < notes * (L::knots + 1);)
            {
                const auto note = job / (L::knots + 1), k = job % (L::knots + 1);
                db[(size_t) job] = meanDb (L::first + note, (double) k / L::knots);
            }
        });
    for (auto& t : pool)
        t.join();

    const auto level = [&] (int note, int k) { return db[(size_t) (note * (L::knots + 1) + k)]; };
    if (argc > 3)
        if (auto* csv = std::fopen (argv[3], "w"))
        {
            for (int n = 0; n < notes; ++n)
            {
                std::fprintf (csv, "%d", L::first + n);
                for (int k = 0; k <= L::knots; ++k)
                    std::fprintf (csv, ",%.3f", level (n, k));
                std::fprintf (csv, "\n");
            }
            std::fclose (csv);
        }
    std::vector<double> anchor ((size_t) notes);
    for (int n = 0; n < notes; ++n)
    {
        if (L::first + n >= violinFirst)
        {
            anchor[(size_t) n] = level (n, 0);
            continue;
        }
        auto gap = 0.0;
        auto count = 0;
        for (int m = std::max (0, n - gapSmooth); m <= std::min (notes - 1, n + gapSmooth); ++m, ++count)
            gap += level (m, 0) - level (m, L::knots);
        anchor[(size_t) n] = level (n, L::knots) + gap / count;
    }

    // (past the fitted bodies: the knots beyond, the span's ends as measured above)
    std::vector<std::vector<double>> beyond ((size_t) notes, std::vector<double> ((size_t) beyondJobs));
    runJobs (notes * (beyondJobs - 2), threads, [&] (int job)
    {
        const auto n = job / (beyondJobs - 2), k = 2 + job % (beyondJobs - 2);
        beyond[(size_t) n][(size_t) k] = meanDb (L::first + n, beyondU (k));
    });
    std::vector<std::string> rows;
    std::vector<double> atCello ((size_t) notes);
    for (int n = 0; n < notes; ++n)
    {
        beyond[(size_t) n][0] = level (n, 0);
        beyond[(size_t) n][1] = level (n, L::knots);
        const auto from = level (n, 0), to = anchor[(size_t) n];
        std::string row = "        {";
        char buffer[96];
        for (int k = 1; k <= L::knots; ++k)
        {
            const auto x = std::min (1.0, (double) k / L::knots / easeTo);
            const auto target = from + (to - from) * x * x * (3.0 - 2.0 * x);
            std::snprintf (buffer, sizeof (buffer), " %.2ff%s", target - level (n, k), k < L::knots ? "," : "");
            row += buffer;
            if (k == L::knots)
                atCello[(size_t) n] = std::atof (buffer + 1);
        }
        std::snprintf (buffer, sizeof (buffer), " }%s   // %d: %.2f dB at the violin's size, %.2f at the cello's, held at %.2f", n < notes - 1 ? "," : "",
                       L::first + n, from, level (n, L::knots), to);
        rows.push_back (row + buffer);
    }
    if (! writeHeader (argv[1], rows, atCello, beyond))
        return 1;
    return 0;
}
