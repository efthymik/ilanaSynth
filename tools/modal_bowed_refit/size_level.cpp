// Measures Modal Bowed's loudness along SIZE and writes src/dsp/ModalBowedSizeLevel.h.
//
// For each MIDI note (ModalBowedSizeLevel::first..last) a held bowed note at
// the Physical card's defaults (as ModalBowed's own bench: DECAY 0.75, DAMP
// 0.35, GRIP and SPEED 0.5, VIBRATO 0.5, velocity 0.8), rendered without
// sizeLevelDb at u = k / knots (size 2.1 ^ u), three seeds, its mean square
// over 1.0-3.5 s. The table is the note's anchor less the dB at each knot
// k 1..knots, so the note keeps one level along SIZE. The anchor is the
// violin's level (u 0) from violinFirst up (the violin's table: its scored
// level); under it, where the violin's size plays notes no violin has, the
// cello's level plus the violin-cello gap smoothed over +-gapSmooth notes (so
// the cello keeps its own note-to-note levels and no note jumps), eased in
// from the violin's own level over u 0..easeTo (smoothstep). Rerun it
// whenever a round changes the fit:
//
//   g++ -O2 -std=c++20 -Isrc -I<juce>/modules -DJUCE_GLOBAL_MODULE_SETTINGS_INCLUDED=1 \
//       -DJUCE_STANDALONE_APPLICATION=1 -DNDEBUG tools/modal_bowed_refit/size_level.cpp -o size_level -lpthread
//   ./size_level src/dsp/ModalBowedSizeLevel.h [threads] [levels.csv]

#include "dsp/ModalBowed.h"
#include <atomic>
#include <cstdio>
#include <cstdlib>
#include <memory>
#include <thread>
#include <vector>

namespace juce
{
    // (juce_core's header only: the release-mode marker it links against)
    this_will_fail_to_link_if_some_of_your_compile_units_are_built_in_release_mode::this_will_fail_to_link_if_some_of_your_compile_units_are_built_in_release_mode() noexcept {}
}

static double levelDb (int midi, double u, float seed)
{
    constexpr double rate = 48000.0;
    auto m = std::make_unique<ModalBowed>();
    m->prepare (rate);
    m->setSizeLevel (false);
    m->setShape ((float) std::pow (ModalBowedBodies::cello, u), 1.0f);
    m->setParams (0.75f, 0.35f, 0.0f, 0.0f, 0.5f, 0.5f, 0.0f, false, false, 0.5f, 0.0f);
    m->setNote (440.0 * std::pow (2.0, (midi - 69) / 12.0));
    m->trigger (0.8f, seed);
    auto sum = 0.0;
    const auto from = (int) (1.0 * rate), to = (int) (3.5 * rate);
    for (int i = 0; i < to; ++i)
    {
        const auto v = (double) m->process (0.0f, true);
        if (i >= from)
            sum += v * v;
    }
    return 10.0 * std::log10 (sum / (to - from) + 1.0e-30);
}

int main (int argc, char** argv)
{
    if (argc < 2) { std::fprintf (stderr, "usage: size_level out.h [threads] [levels.csv]\n"); return 1; }
    using L = ModalBowedSizeLevel;
    const int threads = argc > 2 ? std::atoi (argv[2]) : 3;
    const int notes = L::last - L::first + 1;
    constexpr float seeds[] { 0.37f, 0.71f, 0.13f };
    constexpr int violinFirst = 55, gapSmooth = 4;
    constexpr double easeTo = 0.25;
    ModalBowedLayers::bankFor (48000.0);
    ModalBowedLayers::waitUntilBuilt();
    std::vector<double> db ((size_t) (notes * (L::knots + 1)), 0.0);
    std::atomic<int> next { 0 };
    std::vector<std::thread> pool;
    for (int t = 0; t < threads; ++t)
        pool.emplace_back ([&]
        {
            for (int job; (job = next++) < notes * (L::knots + 1);)
            {
                const auto note = job / (L::knots + 1), k = job % (L::knots + 1);
                // (power mean over the seeds)
                auto power = 0.0;
                for (auto seed : seeds)
                    power += std::pow (10.0, levelDb (L::first + note, (double) k / L::knots, seed) / 10.0) / std::size (seeds);
                db[(size_t) job] = 10.0 * std::log10 (power);
            }
        });
    for (auto& t : pool)
        t.join();

    const auto level = [&] (int note, int k) { return db[(size_t) (note * (L::knots + 1) + k)]; };
    if (argc > 3)
        if (auto* csv = std::fopen (argv[3], "w"))
        {
            for (int n = 0; n < notes; ++n)
            {
                std::fprintf (csv, "%d", L::first + n);
                for (int k = 0; k <= L::knots; ++k)
                    std::fprintf (csv, ",%.3f", level (n, k));
                std::fprintf (csv, "\n");
            }
            std::fclose (csv);
        }
    std::vector<double> anchor ((size_t) notes);
    for (int n = 0; n < notes; ++n)
    {
        if (L::first + n >= violinFirst)
        {
            anchor[(size_t) n] = level (n, 0);
            continue;
        }
        auto gap = 0.0;
        auto count = 0;
        for (int m = std::max (0, n - gapSmooth); m <= std::min (notes - 1, n + gapSmooth); ++m, ++count)
            gap += level (m, 0) - level (m, L::knots);
        anchor[(size_t) n] = level (n, L::knots) + gap / count;
    }

    auto* out = std::fopen (argv[1], "w");
    if (out == nullptr) { std::fprintf (stderr, "can't write %s\n", argv[1]); return 1; }
    std::fprintf (out, "// Generated by tools/modal_bowed_refit/size_level.cpp: do not edit.\n#pragma once\n\n"
                       "// SIZE's loudness for Modal Bowed: per MIDI note (first..last, held past\n"
                       "// either end), the dB at u = k / knots (k 1..knots; 0 at k 0, held past\n"
                       "// knots) that keeps a bowed note at one level along SIZE, the violin's\n"
                       "// (its anchor). See ModalBowed::sizeLevelDb.\n"
                       "struct ModalBowedSizeLevel\n{\n"
                       "    static constexpr int knots = %d, first = %d, last = %d;\n"
                       "    static constexpr float db[last - first + 1][knots] {\n", L::knots, L::first, L::last);
    for (int n = 0; n < notes; ++n)
    {
        const auto from = level (n, 0), to = anchor[(size_t) n];
        std::fprintf (out, "        {");
        for (int k = 1; k <= L::knots; ++k)
        {
            const auto x = std::min (1.0, (double) k / L::knots / easeTo);
            const auto target = from + (to - from) * x * x * (3.0 - 2.0 * x);
            std::fprintf (out, " %.2ff%s", target - level (n, k), k < L::knots ? "," : "");
        }
        std::fprintf (out, " }%s   // %d: %.2f dB at the violin's size, %.2f at the cello's, held at %.2f\n", n < notes - 1 ? "," : "",
                      L::first + n, from, level (n, L::knots), to);
    }
    std::fprintf (out, "    };\n};\n");
    std::fclose (out);
    return 0;
}
