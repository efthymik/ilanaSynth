#!/usr/bin/env bash
# Regenerates src/gpu/VulkanShaders.h from src/gpu/shaders/ui.vert and ui.frag
# (needs glslangValidator: apt install glslang-tools, or the Vulkan SDK). The
# header is committed, so building the plugin needs no shader compiler.
set -euo pipefail
cd "$(dirname "$0")/../src/gpu"
tmp=$(mktemp -d)
glslangValidator -V --target-env vulkan1.0 --vn ilanaUiVert -o "$tmp/vert.h" shaders/ui.vert > /dev/null
glslangValidator -V --target-env vulkan1.0 --vn ilanaUiFrag -o "$tmp/frag.h" shaders/ui.frag > /dev/null
{
    echo "#pragma once"
    echo "// Generated by tools/build_vulkan_shaders.sh from src/gpu/shaders: do not edit."
    echo "#include <cstdint>"
    sed -e 's/^const uint32_t/inline const uint32_t/' -e '/#pragma once/d' "$tmp/vert.h" "$tmp/frag.h"
} > VulkanShaders.h
rm -rf "$tmp"
echo "wrote src/gpu/VulkanShaders.h"
